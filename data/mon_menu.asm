DEF NUM_MONMENUVALUES EQU const_value - 1

MonMenuOptionStrings:
; entries correspond to MONMENUVALUE_* constants
	list_start MOVE_NAME_LENGTH - 2
	li "STATS"
	li "SWITCH"
	li "ITEM"
	li "CANCEL"
	li "MOVE"
	li "MAIL"
	li "ERROR!"
	assert_list_length NUM_MONMENUVALUES

MACRO mon_menu_move
; category, item, the move (its 16-bit index)
	db \1, \2
	dw \3
ENDM

MACRO mon_menu_option
; category, item, value
	db \1, \2, \3, 0
ENDM

MonMenuOptions:
; category, item, value; actions are in PokemonActionSubmenu (see engine/pokemon/mon_menu.asm)
